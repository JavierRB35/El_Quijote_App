import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const browser = await chromium.launch({channel:process.env.QA_BROWSER_CHANNEL || 'msedge',headless:true});
const context = await browser.newContext({viewport:{width:1366,height:768},reducedMotion:'reduce'});
const page = await context.newPage();
const errores = [];
page.on('pageerror', e => errores.push(e.message));
await page.goto('http://127.0.0.1:1420/');
await page.getByRole('button',{name:/Modo Historia/}).click();
await page.getByRole('button',{name:'Siguiente intervención (enter)'}).click();
const texto = await page.locator('.texto').innerText();
await page.getByRole('button',{name:'Ajustes de texto y movimiento'}).click();
await page.keyboard.press('Escape');
assert.equal(await page.locator('.ajustes-panel').count(),0);
assert.equal(await page.locator('.texto').innerText(),texto);
await page.getByRole('button',{name:'Descubrir más',exact:true}).click();
await page.getByRole('dialog').waitFor();
await page.keyboard.press('ArrowRight');
await page.keyboard.press('r');
assert.equal(await page.locator('.texto').innerText(),texto);
await page.keyboard.press('Escape');
assert.equal(await page.getByRole('dialog').count(),0);
assert.equal(await page.getByRole('button',{name:'Descubrir más',exact:true}).evaluate(e=>e===document.activeElement),true);
await page.getByRole('button',{name:'Volver al menú (escape)'}).click();
await page.getByRole('button',{name:/Modo Historia/}).click();
assert.equal(await page.locator('.texto').innerText(),texto,'recuperación de Historia');
await page.getByRole('button',{name:'Volver al menú (escape)'}).click();
await page.getByRole('button',{name:/Modo Aventura/}).click();
await page.locator('.an-opcion').first().click();
const resultado = await page.locator('.an-panel').innerText();
await page.getByRole('button',{name:'Menú',exact:true}).click();
await page.getByRole('button',{name:/Modo Aventura/}).click();
assert.equal(await page.locator('.an-panel').innerText(),resultado,'recuperación de Aventura');
await page.getByRole('button',{name:'Menú',exact:true}).click();
// Fallo real de la petición de imagen, sin alterar ni borrar ningún activo.
await page.route('**/__dev/asset?*',route=>route.abort());
await page.getByRole('button',{name:/Modo Historia/}).click();
await page.getByText('Imagen no disponible.',{exact:true}).waitFor();
assert.equal(await page.locator('.texto').innerText(),texto);
await page.getByRole('button',{name:'Ocultar texto',exact:true}).click();
await page.getByRole('button',{name:'Mostrar texto',exact:true}).click();
assert.equal(await page.locator('.texto').innerText(),texto);
await page.screenshot({path:resolve(import.meta.dirname,'../../docs/qa/dc37/evidencias/fallo-imagen-1366.png')});
await page.route('**/__dev/paquete',route=>route.fulfill({status:503,body:'QA: indisponible'}));
await page.reload();
await page.getByRole('button',{name:'Reintentar'}).waitFor();
await page.unroute('**/__dev/paquete');
await page.getByRole('button',{name:'Reintentar'}).click();
await page.getByRole('button',{name:/Modo Historia/}).waitFor();
assert.deepEqual(errores,[]);
const resultadoQA={estado:'PASS',pruebas:['Esc de ajustes sin salir','diálogo: foco, teclado y Esc','recuperación Historia','recuperación Aventura','fallo de imagen sin perder texto ni control','error de catálogo y reintento'],errores_consola:errores};
await writeFile(resolve(import.meta.dirname,'../../docs/qa/dc37/evidencias/recuperacion.json'),JSON.stringify(resultadoQA,null,2)+'\n');
console.log(resultadoQA);
await browser.close();
